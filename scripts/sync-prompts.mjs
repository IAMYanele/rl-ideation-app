// Copies Yanele's scripting frameworks and the client profiles into lib/prompts.generated.ts.
// Run `npm run sync-prompts` after editing any skill in workflow-agents/scripter, then redeploy.
import fs from "node:fs";
import path from "node:path";

const SCRIPTER = process.env.SCRIPTER_DIR || "C:/Users/yanel/Documents/ai.agents/workflow-agents/scripter";
const read = (p) => fs.readFileSync(path.join(SCRIPTER, p), "utf8");
const local = (p) => fs.readFileSync(new URL("../" + p, import.meta.url), "utf8");

const bundle = {
  analyzer: read("skills/script-analyzer-beginner/SKILL.md"),
  writer: read("clients/nick perry/SKILL-nick-v3-improved.md"),
  optimizer: read("skills/script-optimizer/SKILL.md"),
  checker: read("skills/script-checker/SKILL.md"),
  profiles: {
    omer: read("clients/omer/client_guidelines.txt"),
    esteban: local("profiles/esteban.md"),
    hireremotelatinos: local("profiles/hireremotelatinos.md"),
  },
};

const out = "// GENERATED by scripts/sync-prompts.mjs. Do not edit by hand.\n" +
  "export const PROMPTS = " + JSON.stringify(bundle, null, 0) + " as const;\n";
fs.writeFileSync(new URL("../lib/prompts.generated.ts", import.meta.url), out);
const kb = (s) => Math.round(s.length / 1024);
console.log("prompts synced:", Object.entries(bundle).filter(([k]) => k !== "profiles").map(([k, v]) => `${k} ${kb(v)}KB`).join(", "));
